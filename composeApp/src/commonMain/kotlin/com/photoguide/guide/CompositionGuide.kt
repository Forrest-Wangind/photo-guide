package com.photoguide.guide

/**
 * 取景参考线（常用构图工具）。
 *
 * 这些都是**纯几何叠加层**：不需要感知层、不需要模型、不进帧通路，
 * 所以在 Phase 1 就能全部落地，而且双端共用同一份绘制代码。
 *
 * ⚠️ 刻意不做"水平仪"：它需要读加速度计（Android SensorManager / iOS CoreMotion），
 * 属于平台 expect/actual + 校准与补偿，是独立一块工作，不能顺手塞进这里。
 * 需要时单独加，并且必须标注"未在本机验证"（本项目无 iOS 编译环境）。
 *
 * [tip] 是选中的那一句用法提示 —— 参考线只画线不解释，等于把工具丢给不会用的人。
 *
 * [promptHint] 给**模型**看：让它的位置建议直接引用屏幕上真实存在的线，
 * 而不是"稍微往左一点"这种对不上所见的话。参考线和台词就此闭环 ——
 * 用户抬眼能看到那条线，也听得到"把眼睛放到右上交点"。
 */
enum class CompositionGuide(
    val displayName: String,
    val tip: String,
    val promptHint: String,
) {
    /** 关闭。不显示任何参考线。 */
    NONE("关闭", "不显示参考线，画面最干净", "无参考线"),

    /** 三分线：最通用的构图基线。 */
    THIRDS(
        "三分线",
        "主体压在线上，眼睛落在四个交点之一",
        "三分线：画面被 3×3 等分，四个交点分别在宽度和高度的 1/3、2/3 处",
    ),

    /** 黄金分割：比三分法收得更紧，主体更靠近中心一点。 */
    GOLDEN(
        "黄金分割",
        "主体放 0.618 线或交点，比三分法更紧凑",
        "黄金分割线：四条 0.382 / 0.618 的虚线，四个交点比三分线交点更靠近画面中心",
    ),

    /** 中心十字：对称、正面、仪式感。 */
    CENTER(
        "中心十字",
        "对称构图，主体压在中心线上",
        "中心十字：一条竖直中线 + 一条水平中线，交点就是画面正中心",
    ),

    /** 对角线：动势与纵深。 */
    DIAGONAL(
        "对角线",
        "沿对角线安排走向，画面更有张力",
        "对角线：左上到右下、左下到右上两条斜线，中心有十字标记",
    ),

    /** 黄金螺旋：主体放在螺旋收紧的"眼睛"附近。 */
    SPIRAL(
        "黄金螺旋",
        "主体放在螺旋中心，视线顺着螺旋收拢",
        "黄金螺旋：内接黄金矩形的分块弧线，螺旋收敛的\"眼睛\"偏在画面一侧",
    ),

    /** 安全框：给后期裁切留余量（封面图/竖版二创）。 */
    SAFE_FRAME(
        "安全框",
        "四周留 8% 余量，后期裁切不丢关键内容",
        "安全框：四周内缩 8% 的方框，框内才是后期裁切后仍然保留的区域（是裁切提示，不是构图线）",
    ),
}
